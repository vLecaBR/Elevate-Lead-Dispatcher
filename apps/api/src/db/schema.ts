import { sql } from 'drizzle-orm';
import {
  bigint,
  boolean,
  check,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

// Every timestamp is timestamptz: the database stores instants, APP_TIMEZONE only matters
// when grouping by day.
const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

export const leadStatus = pgEnum('lead_status', [
  'new',
  'contacted',
  'no_answer',
  'callback',
  'qualified',
  'sale',
  'refund',
  'invalid',
]);
export const eventSource = pgEnum('event_source', ['system', 'webhook', 'operator']);
export const userRole = pgEnum('user_role', ['ADMIN', 'OPERATOR']);

export const products = pgTable('products', {
  id: uuid('id').primaryKey().defaultRandom(),
  slug: text('slug').notNull().unique(),
  name: text('name').notNull(),
  isActive: boolean('is_active').notNull().default(true),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const funnels = pgTable(
  'funnels',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    productId: uuid('product_id')
      .notNull()
      .references(() => products.id),
    slug: text('slug').notNull(),
    name: text('name').notNull(),
    isActive: boolean('is_active').notNull().default(true),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
  },
  (t) => [unique('funnels_product_id_slug_unique').on(t.productId, t.slug)],
);

export const affiliates = pgTable('affiliates', {
  id: uuid('id').primaryKey().defaultRandom(),
  externalCode: text('external_code').notNull().unique(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const callCenters = pgTable(
  'call_centers',
  {
    // Integer identity (not uuid): the dispatcher locks and tie-breaks by `ORDER BY id`,
    // so creation order must define that order deterministically.
    id: integer('id').primaryKey().generatedAlwaysAsIdentity(),
    slug: text('slug').notNull().unique(),
    name: text('name').notNull(),
    weight: integer('weight').notNull(),
    isActive: boolean('is_active').notNull().default(true),
    // Smooth Weighted Round Robin state (PLAN.md §8).
    dispatchCredit: bigint('dispatch_credit', { mode: 'number' }).notNull().default(0),
    webhookSecret: text('webhook_secret').notNull(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (t) => [check('call_centers_weight_check', sql`${t.weight} >= 0`)],
);

export const leads = pgTable('leads', {
  // UUIDv7 generated by the application (time-ordered: better index locality than v4).
  id: uuid('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull(),
  phoneE164: text('phone_e164').notNull(),
  productId: uuid('product_id')
    .notNull()
    .references(() => products.id),
  funnelId: uuid('funnel_id')
    .notNull()
    .references(() => funnels.id),
  affiliateId: uuid('affiliate_id').references(() => affiliates.id),
  source: text('source'),
  campaign: text('campaign'),
  utmSource: text('utm_source'),
  utmMedium: text('utm_medium'),
  utmCampaign: text('utm_campaign'),
  utmContent: text('utm_content'),
  utmTerm: text('utm_term'),
  // Projection of lead_status_events, recomputed by the reducer (PLAN.md §9.3).
  status: leadStatus('status').notNull().default('new'),
  statusUpdatedAt: timestamptz('status_updated_at').notNull().defaultNow(),
  // Mirrors distributions.call_center_id (written in the same transaction) so the hottest
  // filters can use composite indexes; NULL means pending.
  callCenterId: integer('call_center_id').references(() => callCenters.id),
  distributedAt: timestamptz('distributed_at'),
  dedupeKey: text('dedupe_key').notNull().unique(),
  requestHash: text('request_hash').notNull(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  updatedAt: timestamptz('updated_at').notNull().defaultNow(),
});

export const distributions = pgTable('distributions', {
  id: bigint('id', { mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
  // UNIQUE: at most one distribution per lead even if application code has a bug.
  leadId: uuid('lead_id')
    .notNull()
    .unique()
    .references(() => leads.id),
  callCenterId: integer('call_center_id')
    .notNull()
    .references(() => callCenters.id),
  strategy: text('strategy').notNull(),
  weightsSnapshot: jsonb('weights_snapshot').notNull(),
  externalId: text('external_id'),
  distributedAt: timestamptz('distributed_at').notNull().defaultNow(),
});

export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    // Stored lowercase by the application.
    email: text('email').notNull().unique(),
    passwordHash: text('password_hash').notNull(),
    role: userRole('role').notNull(),
    callCenterId: integer('call_center_id').references(() => callCenters.id),
    isActive: boolean('is_active').notNull().default(true),
    failedLoginCount: integer('failed_login_count').notNull().default(0),
    lockedUntil: timestamptz('locked_until'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
  },
  (t) => [
    // An OPERATOR always has a call center and an ADMIN never has one: an operator
    // without scope cannot exist, so it cannot accidentally see every lead.
    check(
      'users_operator_call_center_check',
      sql`(${t.role} = 'OPERATOR') = (${t.callCenterId} IS NOT NULL)`,
    ),
  ],
);

export const leadStatusEvents = pgTable(
  'lead_status_events',
  {
    id: bigint('id', { mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
    leadId: uuid('lead_id')
      .notNull()
      .references(() => leads.id),
    status: leadStatus('status').notNull(),
    // When the event happened according to its source; ordering key for the reducer.
    eventTs: timestamptz('event_ts').notNull(),
    receivedAt: timestamptz('received_at').notNull().defaultNow(),
    source: eventSource('source').notNull(),
    callCenterId: integer('call_center_id').references(() => callCenters.id),
    actorUserId: uuid('actor_user_id').references(() => users.id),
    externalId: text('external_id'),
    eventKey: text('event_key').notNull(),
    payload: jsonb('payload'),
    note: text('note'),
  },
  // Webhook dedupe: the same event delivered twice inserts once.
  (t) => [unique('lead_status_events_lead_id_event_key_unique').on(t.leadId, t.eventKey)],
);

export const sessions = pgTable('sessions', {
  // sha256 of the cookie token: a database leak does not expose usable sessions.
  tokenHash: text('token_hash').primaryKey(),
  userId: uuid('user_id')
    .notNull()
    .references(() => users.id),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  expiresAt: timestamptz('expires_at').notNull(),
});
